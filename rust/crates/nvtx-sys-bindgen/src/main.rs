//! Regenerates the pre-generated bindings in `nvtx-sys/src/bindings/`, one file per combination
//! of the `cuda` and `cuda_runtime` features. Requires libclang. Run from `rust/` with:
//!
//! ```sh
//! cargo run -p nvtx-sys-bindgen
//! ```
//!
//! The output is portable across targets:
//! - `wchar_t` is not generated; it is defined in `nvtx-sys/src/lib.rs`.
//! - Functions use `extern "system"`, which is `stdcall` on 32-bit x86 Windows (matching
//!   `NVTX_API`) and `C` everywhere else.
//! - C enums are `u32`, which has the same size as the `i32` used by MSVC.

use std::{error::Error, fs, path::Path};

use bindgen::{Abi, AliasVariation, EnumVariation, MacroTypeVariation, RustEdition, RustTarget};

/// The header of the generated files, which must start with the SPDX lines.
const HEADER: &str = "\
// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception

// Generated by `cargo run -p nvtx-sys-bindgen`. Do not edit by hand.

";

/// The features that change the bindings. Their names are also used for the file names.
const FEATURES: [&str; 3] = ["cuda", "cuda_runtime", "tools"];

fn main() -> Result<(), Box<dyn Error>> {
    let sys = Path::new(env!("CARGO_MANIFEST_DIR")).join("../nvtx-sys");
    // Generate one file for every combination of features.
    for mask in 0..1_u8 << FEATURES.len() {
        let enabled: Vec<&str> = FEATURES
            .into_iter()
            .enumerate()
            .filter(|(i, _)| mask & (1 << i) != 0)
            .map(|(_, feature)| feature)
            .collect();
        let name = if enabled.is_empty() {
            "core".to_owned()
        } else {
            enabled.join("_")
        };
        let bindings = builder(&sys, &enabled)?.generate()?;
        fs::write(
            sys.join("src/bindings").join(name).with_extension("rs"),
            format!("{HEADER}{bindings}"),
        )?;
    }
    Ok(())
}

fn builder(sys: &Path, features: &[&str]) -> Result<bindgen::Builder, Box<dyn Error>> {
    let mut builder = bindgen::Builder::default()
        .rust_target(RustTarget::stable(77, 0).map_err(|err| err.to_string())?)
        .rust_edition(RustEdition::Edition2021)
        .header(sys.join("c/include/wrapper.h").display().to_string())
        .clang_args([
            "--target=x86_64-unknown-linux-gnu".to_owned(),
            // only use clang's own headers, so the output does not depend on the host
            "-ffreestanding".to_owned(),
            format!("-I{}", sys.join("c/include").display()),
        ])
        .use_core()
        .layout_tests(false)
        .allowlist_recursively(false)
        .generate_comments(false)
        .generate_cstr(true)
        .default_alias_style(AliasVariation::TypeAlias)
        .default_enum_style(EnumVariation::Rust {
            non_exhaustive: false,
        })
        .constified_enum_module("nvtxResource.*_t")
        .default_macro_constant_type(MacroTypeVariation::Signed)
        .sort_semantically(true)
        .translate_enum_integer_types(true)
        .wrap_unsafe_ops(true)
        // `NVTX_API` is `__stdcall` on Windows, which matches "system". This also applies to the
        // `NvtxFunctionPointer` placeholder, which is declared without `NVTX_API` but must be
        // cast before use. Only use a single ABI override: bindgen picks an arbitrary one when
        // several match.
        .override_abi(Abi::System, ".*")
        // mark any nvtx(...)_t type as required except those starting with nvtxRes
        .must_use_type("nvtx[^R][^e][^s].*_t")
        // permit all nvtx-prefixed types except internal ones
        .allowlist_type("nvtx[^_].*")
        // expose NVTX_VERSION
        .allowlist_var("NVTX_VERSION")
        // expose all nvtx-prefixed functions
        .allowlist_function("nvtx.*")
        // allow cuda types
        .allowlist_type("CU.*")
        .allowlist_type("cuda.*")
        // disallow impl-specific
        .blocklist_type("__.*")
        // `wchar_t` differs between targets and is defined in `nvtx-sys/src/lib.rs`
        .blocklist_type("wchar_t");

    if features.contains(&"cuda") {
        builder = builder.clang_arg("-DENABLE_CUDA");
    }
    if features.contains(&"cuda_runtime") {
        builder = builder.clang_arg("-DENABLE_CUDART");
    }
    if features.contains(&"tools") {
        builder = builder
            // expose the callback-subscription types (export tables, callback
            // modules, and callback ids)
            .allowlist_type("Nvtx.*")
            // expose the dependency-free fake types referenced by the
            // fakeimpl fntypes (required because allowlisting is not recursive)
            .allowlist_type("nvtx_.*")
            // expose the injection result codes
            .allowlist_var("NVTX_SUCCESS")
            .allowlist_var("NVTX_FAIL")
            .allowlist_var("NVTX_ERR_.*");
        // the function-table slot signatures (`*_impl_fntype` and
        // `*_fakeimpl_fntype`) are covered by the "nvtx[^_].*" allowlist above
    } else {
        // disallow any fntypes
        builder = builder.blocklist_type(".*fntype.*");
    }

    Ok(builder)
}
